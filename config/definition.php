<?php

declare(strict_types=1);

use DeviceViewBundle\View\DeviceType;
use DeviceViewBundle\ViewSwitch\SwitchTarget;
use Symfony\Component\Config\Definition\Configurator\DefinitionConfigurator;

// The configuration tree under the device_view root. Each feature adds its own keys.
return static function (DefinitionConfigurator $definition): void {
    $views = array_map(static fn (DeviceType $view): string => $view->value, DeviceType::cases());
    $names = $definition->rootNode()
        ->children()
            ->enumNode('default_view')
                ->info('The view when nothing decides it: no detector answer, an empty user agent, or no request.')
                ->values($views)
                ->defaultValue(DeviceType::Desktop->value)
            ->end()
            ->booleanNode('tablet_as_mobile')
                ->info('Serve the mobile view wherever the tablet view was resolved.')
                ->defaultFalse()
            ->end()
            ->arrayNode('views')
                ->addDefaultsIfNotSet()
                ->children()
                    ->arrayNode('names')
                        ->info('The name of each view in URLs, the remember storage, headers and the DeviceView facade: unique, lowercase letters, digits, "_" and "-".')
                        ->addDefaultsIfNotSet()
                        ->validate()
                            ->always(
                                static function (array $names): array {
                                    // each name is a string: the stringNode children reject anything else
                                    foreach (array_count_values(array_filter($names, is_string(...))) as $name => $count) {
                                        if ($count > 1) {
                                            throw new InvalidArgumentException(sprintf('The view names must be unique: "%s" is used twice.', $name));
                                        }
                                    }

                                    return $names;
                                },
                            )
                        ->end()
                        ->children()
    ;
    foreach ($views as $view) {
        $names
            ->stringNode($view)
                ->defaultValue($view)
                ->validate()
                    ->always(static function (string $name): string {
                        if (1 !== preg_match('/^[a-z0-9_-]+$/D', $name)) {
                            throw new InvalidArgumentException(sprintf('The view name "%s" is invalid: use lowercase letters, digits, "_" and "-" only.', $name));
                        }

                        return $name;
                    })
                ->end()
            ->end()
        ;
    }

    $definition->rootNode()
        ->children()
            ->arrayNode('detector')
                ->info('How the device type is detected when nothing else decides the view.')
                ->addDefaultsIfNotSet()
                ->children()
                    ->stringNode('id')
                        ->info('auto (Mobile Detect when it is installed), mobile_detect, or the id of a service implementing DeviceViewBundle\Detector\DeviceDetectorInterface.')
                        ->defaultValue('auto')
                        ->cannotBeEmpty()
                    ->end()
                    ->arrayNode('mobile_detect')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->arrayNode('headers')
                                ->info('The request headers passed to Mobile Detect, also listed in Vary.')
                                ->defaultValue(['User-Agent'])
                                ->stringPrototype()->cannotBeEmpty()->end()
                                ->validate()
                                    ->ifEmpty()
                                    ->thenInvalid('device_view.detector.mobile_detect.headers must list at least one header.')
                                ->end()
                            ->end()
                            ->scalarNode('cache')
                                ->info('The id of a PSR-16 cache service (Psr\SimpleCache\CacheInterface) for Mobile Detect\'s results, or null.')
                                ->defaultNull()
                                ->validate()
                                    ->ifTrue(static fn (mixed $cache): bool => null !== $cache && (!is_string($cache) || '' === $cache))
                                    ->thenInvalid('device_view.detector.mobile_detect.cache must be null or a service id, got %s.')
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
            ->end()
        ->end()
    ;

    $definition->rootNode()
        ->children()
            ->arrayNode('switch')
                ->info('The switch query parameter: a link to ?device_view=mobile serves the mobile view.')
                ->addDefaultsIfNotSet()
                ->children()
                    ->booleanNode('enabled')
                        ->info('Read the switch parameter on main requests whose method is in redirect.methods.')
                        ->defaultTrue()
                    ->end()
                    ->stringNode('parameter')
                        ->info('The query parameter whose value is a view name.')
                        ->defaultValue('device_view')
                        ->cannotBeEmpty()
                    ->end()
                    ->enumNode('target')
                        ->info('Where a switch redirects: current (the same page without the parameter), home (the base URL and "/"), or none (no redirect: the switch applies to this request only).')
                        ->values(array_map(static fn (SwitchTarget $target): string => $target->value, SwitchTarget::cases()))
                        ->defaultValue(SwitchTarget::Current->value)
                    ->end()
                    ->enumNode('status')
                        ->info('The status of the switch redirect.')
                        ->values([302, 303, 307])
                        ->defaultValue(302)
                    ->end()
                ->end()
            ->end()
            ->arrayNode('redirect')
                ->info('The redirects the bundle answers with.')
                ->addDefaultsIfNotSet()
                ->children()
                    ->arrayNode('methods')
                        ->info('The request methods the switch and the device redirects apply to.')
                        ->defaultValue(['GET', 'HEAD'])
                        ->stringPrototype()
                            ->cannotBeEmpty()
                            ->beforeNormalization()
                                ->ifString()
                                ->then(strtoupper(...))
                            ->end()
                        ->end()
                        ->validate()
                            ->ifEmpty()
                            ->thenInvalid('device_view.redirect.methods must list at least one method.')
                        ->end()
                    ->end()
                    ->scalarNode('cache_control')
                        ->info('The Cache-Control header of every redirect the bundle answers with, or null to leave it alone.')
                        ->defaultValue('no-store, private')
                        ->validate()
                            ->ifTrue(static fn (mixed $value): bool => null !== $value && (!is_string($value) || '' === $value))
                            ->thenInvalid('device_view.redirect.cache_control must be null or a non-empty string, got %s.')
                        ->end()
                    ->end()
                ->end()
            ->end()
        ->end()
    ;

    $definition->rootNode()
        ->children()
            ->arrayNode('remember')
                ->info('Remembering the view between requests (design.md section 7). By default only a switch is remembered, until the browser session ends.')
                ->addDefaultsIfNotSet()
                ->validate()
                    ->always(static function (array $remember): array {
                        /** @var array{storage: string, detected_view: bool, lifetime: int, consented_lifetime: int, cookie: array{secure: bool|string, same_site: string|null}} $remember */
                        if ('none' === $remember['storage'] && $remember['detected_view']) {
                            throw new InvalidArgumentException('device_view.remember.detected_view cannot be true when device_view.remember.storage is "none".');
                        }

                        if ($remember['lifetime'] > 0 && $remember['consented_lifetime'] < $remember['lifetime']) {
                            throw new InvalidArgumentException(sprintf('device_view.remember.consented_lifetime (%d) must be greater than or equal to device_view.remember.lifetime (%d).', $remember['consented_lifetime'], $remember['lifetime']));
                        }

                        if ('none' === $remember['cookie']['same_site'] && false === $remember['cookie']['secure']) {
                            throw new InvalidArgumentException('device_view.remember.cookie.same_site "none" needs device_view.remember.cookie.secure set to true or auto.');
                        }

                        return $remember;
                    })
                ->end()
                ->children()
                    ->stringNode('storage')
                        ->info('Where the view is remembered: cookie, session (the framework session, never started just to read), none, or the id of a service implementing DeviceViewBundle\Remember\ViewStorageInterface.')
                        ->defaultValue('cookie')
                        ->cannotBeEmpty()
                    ->end()
                    ->booleanNode('on_switch')
                        ->info('Remember the view a visitor switches to.')
                        ->defaultTrue()
                    ->end()
                    ->booleanNode('detected_view')
                        ->info('Also remember a view the detector or the trusted header gave, on the first response that uses it.')
                        ->defaultFalse()
                    ->end()
                    ->integerNode('lifetime')
                        ->info('How long the view is remembered without consent, in seconds; 0 keeps it until the browser session ends.')
                        ->min(0)
                        ->defaultValue(0)
                    ->end()
                    ->integerNode('consented_lifetime')
                        ->info('How long the view is remembered when consent is granted, in seconds; at least lifetime unless lifetime is 0.')
                        ->min(0)
                        ->defaultValue(31536000)
                    ->end()
                    ->arrayNode('cookie')
                        ->info('The cookie of the cookie storage.')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->stringNode('name')
                                ->defaultValue('device_view')
                                ->validate()
                                    // an RFC 6265 token without ".", which PHP turns into "_" in cookie names
                                    ->ifTrue(static fn (string $name): bool => 1 !== preg_match('/^[A-Za-z0-9!#$%&\'*+\-^_`|~]+$/D', $name))
                                    ->then(static fn (string $name): never => throw new InvalidArgumentException(sprintf('The cookie name "%s" is invalid.', $name)))
                                ->end()
                            ->end()
                            ->stringNode('path')
                                ->defaultValue('/')
                                ->cannotBeEmpty()
                            ->end()
                            ->scalarNode('domain')
                                ->defaultNull()
                                ->validate()
                                    ->ifTrue(static fn (mixed $domain): bool => null !== $domain && (!is_string($domain) || '' === $domain))
                                    ->thenInvalid('device_view.remember.cookie.domain must be null or a non-empty string, got %s.')
                                ->end()
                            ->end()
                            ->enumNode('secure')
                                ->info('auto adds Secure on HTTPS requests; same_site none always adds it.')
                                ->values(['auto', true, false])
                                ->defaultValue('auto')
                            ->end()
                            ->booleanNode('http_only')
                                ->defaultTrue()
                            ->end()
                            ->enumNode('same_site')
                                ->info('lax, strict, none (needs secure true or auto) or null.')
                                ->values(['lax', 'strict', 'none', null])
                                ->defaultValue('lax')
                            ->end()
                            ->booleanNode('raw')
                                ->info('Write the value without URL encoding.')
                                ->defaultFalse()
                            ->end()
                        ->end()
                    ->end()
                    ->arrayNode('session')
                        ->info('The session storage.')
                        ->addDefaultsIfNotSet()
                        ->children()
                            ->stringNode('key')
                                ->info('The session attribute holding the view name.')
                                ->defaultValue('_device_view')
                                ->cannotBeEmpty()
                            ->end()
                        ->end()
                    ->end()
                ->end()
            ->end()
            ->arrayNode('http_cache')
                ->info('How the bundle keeps HTTP caches from serving a view to the wrong visitor.')
                ->addDefaultsIfNotSet()
                ->children()
                    ->booleanNode('private_when_remembering')
                        ->info('Make a response private when it writes or expires the remember cookie.')
                        ->defaultTrue()
                    ->end()
                ->end()
            ->end()
        ->end()
    ;

    $definition->rootNode()
        ->validate()
            ->ifTrue(static function (array $config): bool {
                /** @var array{remember: array{storage: string}, consent: array{provider: string|null}} $config */
                $consentWithoutStorage = 'none' === $config['remember']['storage'] && null !== $config['consent']['provider'];

                return $consentWithoutStorage;
            })
            ->thenInvalid('device_view.consent.provider cannot be set when device_view.remember.storage is "none".')
        ->end()
        ->children()
            ->arrayNode('consent')
                ->info('Where the consent comes from that remembers the view for remember.consented_lifetime (design.md sections 7 and 8).')
                ->addDefaultsIfNotSet()
                ->children()
                    ->scalarNode('provider')
                        ->info('null (no consent checker), the name of a built-in reader of a consent tool, such as tarteaucitron, or the id of a service implementing DeviceViewBundle\Consent\ConsentCheckerInterface.')
                        ->defaultNull()
                        ->validate()
                            ->ifTrue(static fn (mixed $provider): bool => null !== $provider && (!is_string($provider) || '' === $provider))
                            ->thenInvalid('device_view.consent.provider must be null, the name of a consent reader or a service id, got %s.')
                        ->end()
                    ->end()
                    ->scalarNode('key')
                        ->info('What the built-in reader checks in the consent tool: a service, category, group or purpose; null for the reader\'s default.')
                        ->defaultNull()
                        ->validate()
                            ->ifTrue(static fn (mixed $key): bool => null !== $key && (!is_string($key) || '' === $key))
                            ->thenInvalid('device_view.consent.key must be null or a non-empty string, got %s.')
                        ->end()
                    ->end()
                    ->scalarNode('cookie')
                        ->info('The name, or name prefix, of the consent tool\'s cookie the built-in reader reads; null for the reader\'s default.')
                        ->defaultNull()
                        ->validate()
                            ->ifTrue(static fn (mixed $cookie): bool => null !== $cookie && (!is_string($cookie) || '' === $cookie))
                            ->thenInvalid('device_view.consent.cookie must be null or a non-empty string, got %s.')
                        ->end()
                    ->end()
                ->end()
            ->end()
        ->end()
    ;

    $definition->rootNode()
        ->children()
            ->arrayNode('services')
                ->info('Replace a built-in service with the id of your own service.')
                ->addDefaultsIfNotSet()
                ->children()
                    ->scalarNode('resolver')
                        ->info('The id of a service implementing DeviceViewBundle\Resolver\ViewResolverInterface, or null for the built-in resolver.')
                        ->defaultNull()
                        ->validate()
                            ->ifTrue(static fn (mixed $id): bool => null !== $id && (!is_string($id) || '' === $id))
                            ->thenInvalid('device_view.services.resolver must be null or a service id, got %s.')
                        ->end()
                    ->end()
                ->end()
            ->end()
        ->end()
    ;
};
